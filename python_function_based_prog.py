# Variable Scope (Local vs Global)
# Local Scope Example

a = 10 # Global variable by default
def fun1():
    a = 100 # Local variable overrides inside
    print("Inside:", a)
fun1() # Prints 100
print("Outside:", a) # Prints 10

# Global Keyword Example
a = 10
def fun2():
    global a # Reference the global variable
    a = 100 # Modifies global variable directly
    print("Inside:", a)
fun2() # Prints 100
print("Outside:", a) # Prints 100 (Modified!)

''' A Higher-Order Function (HOF) is a function that does at least one of these two things:
1. Accepts another function as an argument.
2. Returns another function as its result.
'''
def fun1():
  print("fun1 is executed")

def fun2(arg):
  print(arg)
  #arg()
fun2(fun1()) # fun1() it's holding a value
fun2(fun1)  # if pass fun1 alone it refer the memory area where the function beging stored

#HOF Type2: A function that can return another function as an output
def parent():
    print("parent is running with some logic & returning child")
    def child(a):
        print(f"child is running now with a param of {a}")
    return child
childvar=parent()#run parent & returns child
childvar(100)

#HOF Type1 : A Function take another function as an argument
def bonus_calc(sal):
    return sal*.10
def inc_calc(sal):
    return 3000

def total_sal(sal,fun):
    bonus_inc_sal=fun(sal)#HOF type1
    final_sal=sal+bonus_inc_sal
    return final_sal
print(total_sal(10000,bonus_calc))#HOF type1
print(total_sal(20000,inc_calc))#HOF type1

