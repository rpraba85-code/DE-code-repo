# there are several ways to pass arguments when calling a function.
''' 1. Positional Arguments
Arguments are passed according to their position/order.
'''
def employee(name, salary):
    print("Name:", name)
    print("Salary:", salary)

employee("Praba", 50000)

''' 2. Keyword Arguments
Instead of depending on position, explicitly specify the parameter name.
'''
def employee(name, salary):
    print("Name:", name)
    print("Salary:", salary)

employee(name="Praba", salary=50000)

#Now order doesn't matter:

employee(salary=50000, name="Praba")

'''3. Default Arguments
a. You can provide a default value for a parameter.
b. Default parameter values are used at last position in the parameter list.
'''
def employee(name,city="Bangalore"):
    print("Name:", name)
    print("City:", city)

employee("Praba")
employee("Praba","Chennai")  # You can override it

# Another example
def calculate_salary(salary, bonus=5000):
    return salary + bonus

print(calculate_salary(50000))

print(calculate_salary(50000, 10000))

''' 4. Variable-Length Arguments — *args

a. Sometimes you don't know how many positional arguments will be passed.
b. *args collects all positional arguments into a tuple.
'''
def add(*args):
    print(args)

add(10,20)
add(10,20,30)

# Practical example
def add(*args):
    total = 0

    for number in args:
        total = total + number
    return total


print(add(10, 20))
print(add(10, 20, 30))
print(add(10, 20, 30, 40))

''' 5. Variable-Length Keyword Arguments — **kwargs
a. Suppose you don't know how many keyword arguments will be passed.
b. **kwargs collects all keyword arguments into a dictionary.
'''
def emp(**kwargs):
    print(kwargs)

emp(name="Praba", salary=50000) # call function

emp(
    name="Praba",
    salary=50000,
    city="Bangalore",
    experience=10
)

